"""LibreLane output: pad ring part of config.yaml, pad_cfg.tcl, chip_top.sv and bondplan PINOUT.

The generated ``pad_cfg.tcl`` replaces LibreLane's ``PAD_CFG`` script: instead of spreading
the pads evenly it places every IO cell exactly where the planner shows it, keeps a gap in
the IO ring at each power split and then fills, connects and bonds the ring like the
original script. ``chip_top.sv`` instantiates the IO cells with the same instance names as
the PAD_* lists, so both always match.
"""

import json
import os
import re
from collections import Counter, OrderedDict
from pathlib import Path

from .. import __version__
from ..model.constants import POWER_FUNCTIONS, SIDE_NAMES
from ..model.pdk import get_package, get_pdk

SIGNAL_FUNCTIONS = ("in", "out", "tri", "inout", "analog")
# LibreLane pad rows: side → (list name, row name, lists bottom→top for vertical rows)
ROWS = {"B": ("PAD_SOUTH", "IO_SOUTH"), "R": ("PAD_EAST", "IO_EAST"),
        "T": ("PAD_NORTH", "IO_NORTH"), "L": ("PAD_WEST", "IO_WEST")}
ROW_ORDER = ("B", "R", "T", "L")
# core-side net suffix per pin role
NET_SUFFIX = {"in": "p2c", "out": "c2p", "oe": "c2p_en", "analog": "padres"}
CORE_PORT_SUFFIX = {"in": "_i", "out": "_o", "oe": "_oe", "analog": ""}
CORE_PORT_DIR = {"in": "input", "out": "output", "oe": "output", "analog": "inout"}
BUS_RE = re.compile(r"^(.*?)\[(\d+)\]$")


def _ident(text):
    t = re.sub(r"\W", "_", text.strip()).strip("_") or "pad"
    return "p_" + t if t[0].isdigit() else t


class PadNames:
    """Instance, port and net names of all pads (shared by every generated file)."""

    def __init__(self, layout):
        self.inst = {}     # pin no → instance name
        self.port = {}     # pin no → (base, index or None) of the top-level *_PAD port
        self.label = {}    # pin no → die pad label (port or rail net), as the bondplan sees it
        self.notes = []
        used_ports = set()
        counts = Counter(_ident(p.name) for p in layout.pins)
        seen = Counter()
        for p in layout.pins:
            if not p.cell:
                continue
            ident = _ident(p.name)
            k = seen[ident]
            seen[ident] += 1
            self.inst[p.no] = f"pad_{ident}" + (f"_{k}" if counts[ident] > 1 else "")
            if p.function in POWER_FUNCTIONS:
                self.label[p.no] = layout.rail(p.function, p.domain)
                continue
            m = BUS_RE.match(p.name)
            base, index = (_ident(m.group(1)), int(m.group(2))) if m else (ident, None)
            key = (base, index)
            n = 2
            while key in used_ports:  # duplicate signal name: keep the port unique
                key = (f"{base}_{n}", index)
                n += 1
            if key != (base, index):
                self.notes.append(f"pin {p.no} {p.name}: duplicate signal, port renamed to {key[0]}_PAD")
            used_ports.add(key)
            self.port[p.no] = key
            self.label[p.no] = f"{key[0]}_PAD" + (f"[{key[1]}]" if key[1] is not None else "")


def _require_pdk(layout):
    pdk = get_pdk(layout.pdk)
    if pdk is None:
        raise ValueError("select a PDK first: the LibreLane output needs IO cells")
    return pdk


def _row_pins(layout, side):
    """Pins with an IO cell on one side in LibreLane list order (left→right, bottom→top)."""
    pins = [p for p in layout.pins_on(side) if p.cell]
    key = (lambda p: p.x) if side in "TB" else (lambda p: p.y)
    return sorted(pins, key=key)


def _ring_low(layout, rc):
    """Lower/left edge of a ring cell along its row, die coordinates (origin lower-left)."""
    start = layout.start(rc.side)
    return start + rc.a if rc.side in "TB" else layout.die_height - (start + rc.b)


def _row_entries(layout, side, names):
    """``(instance, comment)`` of the cells of one side in LibreLane list order."""
    entries = []
    for p in _row_pins(layout, side):
        dom = f", domain {p.domain}" if p.domain else ""
        entries.append((p.x if side in "TB" else p.y, names.inst[p.no], f"pin {p.no} {p.name} ({p.cell}{dom})"))
    for rc in layout.ring_cells:
        if rc.side == side:
            entries.append((_ring_low(layout, rc) + (rc.b - rc.a) / 2, rc.name, f"{rc.master}, not a pad"))
    return [(inst, note) for _, inst, note in sorted(entries)]


def _header(comment, layout, pdk, source):
    src = f" from {source}" if source else ""
    return [f"{comment} Generated by PREP-IC {__version__}{src}. Do not edit by hand,",
            f"{comment} change the pad ring in PREP-IC and export again. PDK: {pdk.name}."]


# ---------------------------------------------------------------- config.yaml

def config_yaml(layout, source=""):
    pdk = _require_pdk(layout)
    names = PadNames(layout)
    W, Hh, m = layout.die_width, layout.die_height, layout.ring_depth + pdk.core_margin
    out = _header("#", layout, pdk, source)
    out += ["# Pad ring part of the LibreLane config.yaml (flow: Chip). Copy it into your config",
            "# and keep pad_cfg.tcl next to it.", "",
            f"DIE_AREA: [0, 0, {W:g}, {Hh:g}]",
            f"CORE_AREA: [{m:g}, {m:g}, {W - m:g}, {Hh - m:g}]   # IO ring {layout.ring_depth:g} µm + "
            f"{pdk.core_margin:g} µm for the core power ring", "",
            "# Places the IO cells exactly as planned (instead of spreading them evenly)",
            "PAD_CFG: dir::pad_cfg.tcl", ""]
    for side in ROW_ORDER:
        var = ROWS[side][0]
        order = "left to right" if side in "TB" else "bottom to top"
        entries = _row_entries(layout, side, names)
        out.append(f"# {SIDE_NAMES[side]} side, {order}")
        if not entries:
            out += [f"{var}: []", ""]
            continue
        out.append(f"{var}: [")
        width = max(len(inst) for inst, _ in entries) + 3
        for i, (inst, note) in enumerate(entries):
            item = f'"{inst}"' + ("," if i < len(entries) - 1 else "")
            out.append(f"    {item:<{width}}  # {note}")
        out += ["]", ""]
    domains = layout.domains
    vdd = [layout.rail("vdd", d) for d in domains]
    gnd = [layout.rail("vss", d) for d in domains]
    if len(domains) == 1:
        out += ["# Core supply nets of the IO ring", f"VDD_NETS: [{vdd[0]}]", f"GND_NETS: [{gnd[0]}]",
                'VERILOG_POWER_DEFINE: "USE_POWER_PINS"', ""]
    else:
        out += ["# Power domains: " + ", ".join(domains) + ". Each ring segment has its own rails:",
                "#   " + ", ".join(sorted({layout.rail(f, d) for d in domains for f in POWER_FUNCTIONS})),
                "# Choose which core supply the standard cells use, e.g.:",
                f"# VDD_NETS: [{', '.join(vdd)}]", f"# GND_NETS: [{', '.join(gnd)}]",
                'VERILOG_POWER_DEFINE: "USE_POWER_PINS"', ""]
    for n in names.notes:
        out.append(f"# Note: {n}")
    return "\n".join(out).rstrip() + "\n"


# ---------------------------------------------------------------- pad_cfg.tcl

def pad_cfg_tcl(layout, source=""):
    pdk = _require_pdk(layout)
    names = PadNames(layout)
    Hh = layout.die_height

    def low(p):  # lower/left edge of the IO cell along its row, die coordinates (origin lower-left)
        return (p.x if p.side in "TB" else p.y) - pdk.bondpad_shift(p.function) - pdk.width_of(p.function) / 2

    def gap_low(sp):
        if sp.side in "TB":
            return layout.start(sp.side) + sp.a
        return Hh - (layout.start(sp.side) + sp.b)

    pads = [(ROWS[s][1], names.inst[p.no], low(p)) for s in ROW_ORDER for p in _row_pins(layout, s)]
    pads += [(ROWS[rc.side][1], rc.name, _ring_low(layout, rc)) for rc in layout.ring_cells]
    gaps = [(ROWS[sp.side][1], gap_low(sp), sp.domain) for sp in layout.splits]
    out = _header("#", layout, pdk, source)
    out += [
        "#",
        "# LibreLane PAD_CFG script, based on LibreLane's scripts/openroad/common/pad_cfg.tcl",
        "# (Copyright 2025 LibreLane Contributors, Apache-2.0). Differences: the pads are placed at",
        "# the planned positions, and each power split leaves a gap in the IO ring so that",
        "# connect_by_abutment creates separate rails per power domain.",
        "",
        "source $::env(SCRIPTS_DIR)/openroad/common/set_global_connections.tcl",
        "set_global_connections",
        "",
        'puts "\\[INFO\\] Generating padring (PREP-IC)…"',
        "",
        "set db [ord::get_db]",
        "set block [ord::get_db_block]",
        "",
        "make_io_sites \\",
        "    -horizontal_site $::env(PAD_SITE_NAME) \\",
        "    -vertical_site $::env(PAD_SITE_NAME) \\",
        "    -corner_site $::env(PAD_CORNER_SITE_NAME) \\",
        "    -offset $::env(PAD_EDGE_SPACING) \\",
        "    -rotation_horizontal $::env(PAD_ROTATION_HORIZONTAL) \\",
        "    -rotation_vertical $::env(PAD_ROTATION_VERTICAL) \\",
        "    -rotation_corner $::env(PAD_ROTATION_CORNER)",
        "",
        "# row, instance, lower/left edge in µm (die coordinates)",
        "set prp_pads {",
    ]
    out += [f"    {{{row} {inst} {pos:g}}}" for row, inst, pos in pads]
    out += ["}", "",
            f"# power splits: row, lower/left edge of the gap in µm, domain after the split ({pdk.split_gap or 0:g} µm gap)",
            "set prp_gaps {"]
    out += [f"    {{{row} {pos:g} {dom}}}" for row, pos, dom in gaps]
    out += ["}", "",
            "foreach pad $prp_pads {",
            "    lassign $pad row inst_name pos",
            '    if { [set inst [$block findInst $inst_name]] == "NULL" } {',
            '        puts stderr "\\[ERROR\\] No instance $inst_name found."',
            "        exit 1",
            "    }",
            "    place_pad -row $row -location $pos $inst_name -master [[$inst getMaster] getName]",
            "}",
            "",
            *([] if pdk.split_filler is None else [
                "# Temporary blockers keep the split gaps free of fillers",
                f"set gap_master [$db findMaster {pdk.split_filler}]",
                "set gap_insts {}",
                "set i 0",
                "foreach gap $prp_gaps {",
                "    lassign $gap row pos domain",
                "    set name PRP_SPLIT_GAP_$i",
                "    odb::dbInst_create $block $gap_master $name",
                f"    place_pad -row $row -location $pos $name -master {pdk.split_filler}",
                "    lappend gap_insts $name",
                "    incr i",
                "}",
                ""]),
            "place_corners $::env(PAD_CORNER)",
            "foreach row {IO_NORTH IO_SOUTH IO_WEST IO_EAST} {",
            "    place_io_fill -row $row {*}$::env(PAD_FILLERS)",
            "}",
            *([] if pdk.split_filler is None else [
                "foreach name $gap_insts {",
                "    odb::dbInst_destroy [$block findInst $name]",
                "}",
                ""]),
            'puts "\\[INFO\\] Connecting ring signals…"',
            "connect_by_abutment",
            "",
            *([] if pdk.bondpad_inset is not None else [
                "if { [info exists ::env(PAD_BONDPAD_NAME)] } {",
                "    foreach pad $prp_pads {",
                "        lassign $pad row inst_name pos",
                "        set master_name [[[$block findInst $inst_name] getMaster] getName]",
                "        dict for {master_regex offset} $::env(PAD_BONDPAD_OFFSETS) {",
                "            if {[regexp $master_regex $master_name]} {",
                "                place_bondpad -bond $::env(PAD_BONDPAD_NAME) $inst_name -offset $offset",
                "            }",
                "        }",
                "    }",
                "}",
                ""]),
            "if { [info exists ::env(PAD_PLACE_IO_TERMINALS)] } {",
            "    foreach pad $prp_pads {",
            "        lassign $pad row inst_name pos",
            "        set master_name [[[$block findInst $inst_name] getMaster] getName]",
            "        foreach master_pin $::env(PAD_PLACE_IO_TERMINALS) {",
            "            lassign [split $master_pin /] check_master pin_name",
            "            if {$master_name == $check_master} {",
            "                place_io_terminals $inst_name/$pin_name",
            "                break",
            "            }",
            "        }",
            "    }",
            "}",
            "",
            "remove_io_rows",
            ""]
    return "\n".join(out)


# ---------------------------------------------------------------- chip_top.sv

def _signals(layout, names):
    """Ordered signal ports: base → dict(indices, function, pins)."""
    sig = OrderedDict()
    for p in layout.pins:
        if p.no not in names.port:
            continue
        base, index = names.port[p.no]
        s = sig.setdefault(base, {"indices": [], "function": p.function, "pins": []})
        if index is not None:
            s["indices"].append(index)
        s["pins"].append(p)
    return sig


def _range(s):
    return f"[{max(s['indices'])}:{min(s['indices'])}] " if s["indices"] else ""


def _rails(layout):
    return list(dict.fromkeys(layout.rail(f, d) for d in layout.domains for f in ("iovdd", "iovss", "vdd", "vss")))


def _tied_pins(cell, inst):
    """Connections and wires of the pins a profile ties: a constant, ``None`` for open, ``@PIN`` for a net of this instance."""
    conns, wires = [], []
    for pin, value in cell.get("ties", {}).items():
        if value is None:
            conns.append(f".{pin}()")
        elif value.startswith("@"):
            net = f"{inst}_{value[1:]}"
            wires += [] if net in wires else [net]
            conns.append(f".{pin}({net})")
        else:
            conns.append(f".{pin}({value})")
    return conns, wires


def chip_top_sv(layout, source="", module="chip_top", core_module="chip_core"):
    pdk = _require_pdk(layout)
    names = PadNames(layout)
    sig = _signals(layout, names)
    rails = _rails(layout)
    out = _header("//", layout, pdk, source)
    out += ["// Top level: IO cells of the pad ring and the core. The pad ring itself (fillers,",
            "// corners, bondpads) is placed by LibreLane with pad_cfg.tcl.", "",
            "`default_nettype none", "", f"module {module} ("]
    ports = [f"    inout wire {_range(s)}{base}_PAD" for base, s in sig.items()]
    out.append("`ifdef USE_POWER_PINS")
    out += [f"    inout wire {r}," for r in rails[:-1]] + [f"    inout wire {rails[-1]}" + ("," if ports else "")]
    out.append("`endif")
    out += [line + ("," if i < len(ports) - 1 else "") for i, line in enumerate(ports)]
    out += [");", ""]

    pin_map = {base: pdk.cell(s["function"])[1] for base, s in sig.items()}

    def on_pad(base, role):  # one pin is the bond pad and the core side at once, as in the gf180mcu analog pad
        return role != "pad" and pin_map[base].get(role) == pin_map[base].get("pad")

    roles_of = {}
    for base, s in sig.items():
        roles = [r for r in pdk.cell(s["function"])[1] if r != "pad"]
        roles_of[base] = roles
        for r in roles:
            if not on_pad(base, r):
                out.append(f"    wire {_range(s)}{base}_{NET_SUFFIX[r]};")
    out.append("")

    for p in layout.pins:
        if not p.cell:
            continue
        master, pins = pdk.cell(p.function, p.drive, p.variant)
        pp = pdk.power_pins_of(p.function)
        power = [f".{pin}({layout.rail(f, p.domain)})" for f in ("iovdd", "iovss", "vdd", "vss") for pin in pp.get(f, [])]
        conns = []
        if p.no in names.port:
            base, index = names.port[p.no]
            idx = f"[{index}]" if index is not None else ""
            for role, pin in pins.items():
                if on_pad(base, role):
                    continue
                net = f"{base}_PAD{idx}" if role == "pad" else f"{base}_{NET_SUFFIX[role]}{idx}"
                invert = "~" if role in pdk.cells[p.function].get("active_low", ()) else ""
                conns.append(f".{pin}({invert}{net})")
        tie_conns, tie_wires = _tied_pins(pdk.cells[p.function], names.inst[p.no])
        conns += tie_conns
        out += [f"    wire {w};" for w in tie_wires]
        dom = f", domain {p.domain}" if p.domain else ""
        out += [f"    // pin {p.no}: {p.name} ({SIDE_NAMES[p.side].lower()}{dom})",
                "    (* keep *)", f"    {master} {names.inst[p.no]} ("]
        out.append("`ifdef USE_POWER_PINS")
        out += [f"        {c}," for c in power[:-1]] + [f"        {power[-1]}" + ("," if conns else "")]
        out.append("`endif")
        out += [f"        {c}" + ("," if i < len(conns) - 1 else "") for i, c in enumerate(conns)]
        out += ["    );", ""]

    for rc in layout.ring_cells:
        cell = next(c for c in pdk.ring_cells if c["name"] == rc.name)
        power = [f".{pin}({layout.rail(f, '')})" for f, pins in cell["power_pins"].items()
                 for pin in ([pins] if isinstance(pins, str) else pins)]
        out += [f"    // {rc.name}: ring cell, not a pad", "    (* keep *)", f"    {rc.master} {rc.name} (", "`ifdef USE_POWER_PINS"]
        out += [f"        {c}," for c in power[:-1]] + [f"        {power[-1]}", "`endif", "    );", ""]

    core = []
    for base, s in sig.items():
        for r in roles_of[base]:
            core.append(f".{base}{CORE_PORT_SUFFIX[r]}({base}_{'PAD' if on_pad(base, r) else NET_SUFFIX[r]})")
    core_power = [layout.rail(f, d) for d in layout.domains for f in ("vdd", "vss")]
    out += [f"    {core_module} i_{core_module} ("]
    out.append("`ifdef USE_POWER_PINS")
    out += [f"        .{r}({r})," for r in core_power[:-1]] + [f"        .{core_power[-1]}({core_power[-1]})" + ("," if core else "")]
    out.append("`endif")
    out += [f"        {c}" + ("," if i < len(core) - 1 else "") for i, c in enumerate(core)]
    out += ["    );", "", "endmodule", "", "`default_nettype wire", ""]
    for n in names.notes:
        out.insert(2, f"// Note: {n}")
    return "\n".join(out)


def chip_core_template_sv(layout, source="", core_module="chip_core", macros=()):
    """Port list of the core as instantiated by chip_top.sv, as a starting point."""
    pdk = _require_pdk(layout)
    names = PadNames(layout)
    sig = _signals(layout, names)
    ports = [f"    inout wire {layout.rail(f, d)}" for d in layout.domains for f in ("vdd", "vss")]
    body = []
    for base, s in sig.items():
        for r in [r for r in pdk.cell(s["function"])[1] if r != "pad"]:
            kind = "wire" if r == "analog" else "logic"
            body.append(f"    {CORE_PORT_DIR[r]} {kind} {_range(s)}{base}{CORE_PORT_SUFFIX[r]}")
    out = _header("//", layout, pdk, source)
    out += ["// Template of the core ports expected by chip_top.sv. Copy it into your core and",
            "// fill in the logic; it is not overwritten by later exports of chip_top.sv.", "",
            "`default_nettype none", "", f"module {core_module} ("]
    out.append("`ifdef USE_POWER_PINS")
    out += [p + "," for p in ports[:-1]] + [ports[-1] + ("," if body else "")]
    out.append("`endif")
    out += [b + ("," if i < len(body) - 1 else "") for i, b in enumerate(body)]
    out += [");", "", "    // core logic", ""]
    placed = [m for m in macros if not m.placeholder]
    if placed:
        out += ["    // Macros (place with these instance names, see macros.yaml):"]
        out += [f"    //   {m.macro} {CORE_INSTANCE}.{m.name}" for m in placed] + [""]
    out += ["endmodule", "", "`default_nettype wire", ""]
    return "\n".join(out)


# ---------------------------------------------------------------- macro placement

CORE_INSTANCE = "i_chip_core"  # instance name of the core in chip_top.sv
ORIENTATION = {0: "N", 90: "E", 180: "S", 270: "W"}  # clockwise rotation in the planner
# Views of a LibreLane run directory. Lint takes the first of vh, pnl and nl that a macro has.
VERILOG_VIEWS = (("vh", ("{}.vh", "{}.v")), ("nl", ("{}.nl.v",)), ("pnl", ("{}.pnl.v",)))  # .v: hand-made macros
# view, key, file. LibreLane names a view's folder key.strip("_*"), so the key "nom_*" lives in spef/nom.
CORNER_VIEWS = (("lib", "{corner}", "{name}__{corner}.lib"), ("spef", "{corner}_*", "{name}.{corner}.spef"))


def _macro_views(name, final, path_value):
    """``MACROS`` lines of the views found below ``final``, ``path_value`` writing a file's path."""
    out = []
    for view, files in VERILOG_VIEWS:
        found = [final / view / f.format(name) for f in files if (final / view / f.format(name)).is_file()]
        if found:
            out.append(f"    {view}: [{path_value(found[0])}]")
    if not out:
        out.append("    # no vh, pnl or nl in LibreLane's layout below final/, so lint stops with MODMISSING")
    for view, key, file in CORNER_VIEWS:
        corners = sorted(c.name for c in (final / view).glob("*")
                         if (c / file.format(name=name, corner=c.name)).is_file())
        if corners:
            out.append(f"    {view}:")
            out += [f"      {key.format(corner=c)}: [{path_value(final / view / c / file.format(name=name, corner=c))}]"
                    for c in corners]
    if (final / "lib" / f"{name}.lib").is_file():
        out.append(f'    # final/lib/{name}.lib not exported, it names no corner. If it holds for all of them: lib: {{"*": [...]}}')
    return out


def _num(v):
    """µm with up to three decimals (``:g`` would cut 1790.565 to 1790.56)."""
    t = f"{round(v, 3):.3f}".rstrip("0").rstrip(".")
    return "0" if t in ("-0", "") else t


def macros_yaml(project, layout, out_dir=None, source=""):
    """``MACROS`` part of the LibreLane config: LEF, GDS and the views found per macro, and the placed instances.

    Locations are the lower-left corners of the placed macros in die coordinates (origin
    lower-left); paths are relative to ``out_dir`` (the directory of the config) when given
    and on the same drive, else absolute.
    """
    from ..model.floorplan import core_area, find_lef, macros_by_directory
    pdk = _require_pdk(layout)
    x0, y0, _, _ = core_area(layout)

    def path_value(path):
        # Quoted, since a directory name may hold [ , or #. dir:: would prefix an absolute path.
        if out_dir is not None:
            try:
                return json.dumps("dir::" + Path(os.path.relpath(path, Path(out_dir).resolve())).as_posix(), ensure_ascii=False)
            except ValueError:  # other drive
                pass
        return json.dumps(Path(path).as_posix(), ensure_ascii=False)

    out = _header("#", layout, pdk, source)
    out += ["# Macro placement for the LibreLane config.yaml (flow: Chip). The macros are",
            f"# instantiated inside the core ({CORE_INSTANCE} in chip_top.sv).", "", "MACROS:"]
    skipped = []
    for name, dirs in macros_by_directory(project.floorplan.macros).items():
        ms, *others = dirs.values()
        skipped += [f"# {m.name} not exported: macro {name} already comes from another directory" for g in others for m in g]
        final = Path(ms[0].path).resolve() / "final"
        lef = final / "lef" / f"{name}.lef"
        if not lef.is_file() and find_lef(ms[0].path):  # the file the planner read may be named otherwise
            lef = final / "lef" / find_lef(ms[0].path).name
        out += [f"  {name}:", f"    gds: [{path_value(final / 'gds' / f'{name}.gds')}]", f"    lef: [{path_value(lef)}]"]
        out += _macro_views(name, final, path_value)
        out.append("    instances:")
        for m in ms:
            w, h = m.size()
            out += [f"      {CORE_INSTANCE}.{m.name}:",
                    f"        location: [{_num(x0 + m.x)}, {_num(layout.die_height - (y0 + m.y + h))}]",
                    f"        orientation: {ORIENTATION[m.rot % 360]}"]
    for m in project.floorplan.macros:
        if m.placeholder:
            out.append(f"# placeholder {m.name} (no LEF) not exported")
    out += skipped
    out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------- bondplan PINOUT

def bondplan_yaml(layout, source=""):
    """PACKAGE_NAME and PINOUT for the packaging/bondplan config.yaml."""
    pdk = _require_pdk(layout)
    pkg = get_package(layout.package)
    if pkg is None:
        raise ValueError("select a package first")
    names = PadNames(layout)
    by_pin = {p.package_pin: p for p in layout.pins if p.package_pin and p.no in names.label}
    leads = pkg.leads()
    side_of = {n: s for s, ns in leads.items() for n in ns}
    out = _header("#", layout, pdk, source)
    out += [f"# Bonding for package {pkg.name} ({pkg.pins} pins, pin 1 at the {pkg.pin1},",
            "# counter-clockwise). Copy into the bondplan config.yaml.", "",
            f"PACKAGE_NAME: {pkg.name}", "", "PINOUT:"]
    last = None
    for n in range(1, pkg.pins + 1):
        side = side_of.get(n)
        if side != last:
            out.append(f"  # {SIDE_NAMES[side]} side")
            last = side
        p = by_pin.get(n)
        key = f"{n}:"
        if p:
            item = f'"{names.label[p.no]}"'
            out.append(f"  {key:<4} {item:<24}  # die pin {p.no} {p.name}")
        else:
            out.append(f"  {key:<4} {'~':<24}  # not bonded")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- files

def librelane_files(project, source="", out_dir=None):
    """All generated files as ``{filename: text}``; the bondplan only with a package."""
    layout = project.layout()
    files = {
        "padring_config.yaml": config_yaml(layout, source),
        "pad_cfg.tcl": pad_cfg_tcl(layout, source),
        "chip_top.sv": chip_top_sv(layout, source),
        "chip_core_template.sv": chip_core_template_sv(layout, source, macros=project.floorplan.macros),
    }
    if any(not m.placeholder for m in project.floorplan.macros):
        files["macros.yaml"] = macros_yaml(project, layout, out_dir, source)
    if layout.package:
        files["bondplan_pinout.yaml"] = bondplan_yaml(layout, source)
    return files


def export_librelane(project, directory, source=""):
    """Write the generated files into ``directory``; returns the written paths."""
    d = Path(directory)
    d.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, text in librelane_files(project, source, out_dir=d).items():
        path = d / name
        path.write_text(text, encoding="utf-8")
        paths.append(path)
    return paths
